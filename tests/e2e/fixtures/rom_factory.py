    # 0x0B0..0x0B1: Maker Code (2 bytes)
    clean_maker = maker_code.upper().encode("ascii", "replace")[:2].ljust(2, b"0")
    rom[0xB0:0xB2] = clean_maker

    # 0x0B2: Fixed byte 0x96
    rom[0xB2] = 0x96

    # 0x0B3: Main unit code (0x00)
    rom[0xB3] = 0x00

    # 0x0B4: Device type (0x00)
    rom[0xB4] = 0x00

    # 0x0B5..0x0BB: 7 reserved bytes
    rom[0xB5:0xBC] = b"\x00" * 7

