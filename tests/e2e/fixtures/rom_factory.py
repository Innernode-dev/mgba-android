def calculate_gba_complement(header_bytes: bytes) -> int:
    """Calculate GBA header complement checksum at offset 0xBD."""
    assert len(header_bytes) >= 0xBD, "Header must be at least 0xBD bytes"
    s = sum(header_bytes[0xA0:0xBD])
    complement = (-(0x19 + s)) & 0xFF
    return complement


def verify_gba_complement(header_bytes: bytes) -> bool:
    """Verify that (sum(0xA0..0xBC) + complement + 0x19) mod 256 == 0."""
    if len(header_bytes) < 0xBE:
        return False
    s = sum(header_bytes[0xA0:0xBD])
    chk = header_bytes[0xBD]
    return ((s + chk + 0x19) & 0xFF) == 0


def create_gba_rom(
    title: str = "TESTGAME",
    game_code: str = "AGBE",
    maker_code: str = "01",
    version: int = 0,
    size_bytes: int = 16 * 1024 * 1024,
    corrupt_checksum: bool = False,
    corrupt_logo: bool = False,
) -> bytes:
    """Create a fully compliant Game Boy Advance ROM binary."""
    rom = bytearray(max(size_bytes, 0x200))

    # 0x000..0x003: ARM branch to 0x80000C0 (b 0x80000C0)
    rom[0x00:0x04] = bytes([0x2E, 0x00, 0x00, 0xEA])

    # 0x004..0x09F: Nintendo logo (156 bytes)
    if corrupt_logo:
        rom[0x04:0xA0] = b"\x00" * 156
    else:
        rom[0x04:0xA0] = GBA_LOGO

    # 0x0A0..0x0AB: Title (12 bytes, uppercase ASCII, zero-padded)
    clean_title = title.upper().encode("ascii", "replace")[:12].ljust(12, b"\x00")
    rom[0xA0:0xAC] = clean_title

    # 0x0AC..0x0AF: Game Code (4 bytes)
    clean_code = game_code.upper().encode("ascii", "replace")[:4].ljust(4, b"\x00")
